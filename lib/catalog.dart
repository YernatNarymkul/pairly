Word _w(String slug, String en, String ru) {
  return Word(id: '$slug-${en.replaceAll(' ', '-')}', en: en, ru: ru);
}

Category _cat(
  String slug,
  String title,
  String subtitle,
  IconData icon,
  List<(String, String)> entries,
) {
  return Category(
    slug: slug,
    title: title,
    subtitle: subtitle,
    icon: icon,
    words: [for (final e in entries) _w(slug, e.$1, e.$2)],
  );
}

