final List<Word> kAllWords = [for (final c in kCategories) ...c.words];

const int kRoundSize = 6;

Category? categoryBySlug(String slug) {
  for (final c in kCategories) {
    if (c.slug == slug) return c;
  }
  return null;
}

List<Word> uniquePool(List<Word> words) {
  final seenEn = <String>{};
  final seenRu = <String>{};
  final out = <Word>[];
  for (final word in words) {
    final en = word.en.toLowerCase();
    final ru = word.ru.toLowerCase();
    if (seenEn.contains(en) || seenRu.contains(ru)) continue;
    seenEn.add(en);
    seenRu.add(ru);
    out.add(word);
  }
  return out;
}

List<Word> pickRound(List<Word> words, List<String> masteredIds,
    {int size = kRoundSize}) {
  final mastered = masteredIds.toSet();
  final unlearned = words.where((w) => !mastered.contains(w.id)).toList();
  final pool = unlearned.length >= size ? unlearned : List<Word>.from(words);
  pool.shuffle();
  return pool.take(size.clamp(0, pool.length)).toList();
}

int masteredInCategory(List<Word> words, List<String> masteredIds) {
  final set = masteredIds.toSet();
  return words.where((w) => set.contains(w.id)).length;
}
